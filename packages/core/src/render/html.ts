// it.ktrdiff.core.render.HtmlRenderer — standalone single-file HTML report: no CDN, no network
// access, works offline. All dynamic text is HTML-escaped; secrets were already redacted upstream.
// The report ships the full ChangeSet, and the Quick/Advanced/Custom switcher only shows/hides
// rows client-side, exactly like the engine's mode filter. The CSS and script literals are copied
// verbatim from the Java source: the output must stay byte-equal to the v0.2.0 oracle.

import { javaValueOf } from '../engine/values.ts';
import { CLASSIFICATIONS, isTextBodyChange, type Change } from '../model/change.ts';
import { classificationSummary, hasErrors, type ChangeSet } from '../model/change-set.ts';
import type { DiffConfig } from '../profile/diff-config.ts';
import { applyMode } from '../profile/mode-filter.ts';
import { javaDoubleToString } from '../util/java.ts';

export function renderHtml(changeSet: ChangeSet, config: DiffConfig): string {
  const quick = applyMode(changeSet, { ...config, mode: 'quick' });
  const h: string[] = [];
  const meta = (key: string, def: string): string => changeSet.metadata.get(key) ?? def;

  const title = 'KTRDiff — ' + esc(meta('afterTransformation', 'report'));
  h.push('<!DOCTYPE html>\n<html lang="en">\n<head>\n');
  h.push('<meta charset="utf-8">\n');
  h.push('<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; ',
    'style-src \'unsafe-inline\'; script-src \'unsafe-inline\'; img-src data:;">\n');
  h.push('<meta name="viewport" content="width=device-width, initial-scale=1">\n');
  h.push('<title>', title, '</title>\n');
  h.push('<style>', css(), '</style>\n</head>\n<body>\n');

  h.push('<header><h1>KTRDiff report</h1><p class="files">',
    '<span class="tag before">Previous</span> ',
    esc(meta('beforeTransformation', '?')),
    ' &nbsp;→&nbsp; <span class="tag after">Current</span> ',
    esc(meta('afterTransformation', '?')),
    '</p></header>\n');

  if (hasErrors(changeSet)) {
    h.push('<section class="errors"><h2>Errors</h2><ul>');
    for (const e of changeSet.errors) {
      h.push('<li><code>', esc(e.code), '</code>');
      if (e.side !== null) h.push(' <em>(', esc(e.side), ')</em>');
      h.push(' ', esc(e.message), '</li>');
    }
    h.push('</ul></section>\n</body></html>');
    return h.join('');
  }

  const counts = classificationSummary(changeSet);
  h.push('<section class="summary">');
  summaryCard(h, 'Functional', counts.get('functional') ?? 0, 'functional');
  summaryCard(h, 'Layout', counts.get('layout') ?? 0, 'layout');
  summaryCard(h, 'Metadata', counts.get('metadata') ?? 0, 'metadata');
  summaryCard(h, 'Configuration', counts.get('configuration') ?? 0, 'configuration');
  summaryCard(h, 'Potentially functional', counts.get('potentially-functional') ?? 0, 'potentially-functional');
  summaryCard(h, 'Unknown', counts.get('unknown') ?? 0, 'unknown');
  h.push('</section>\n');

  h.push('<p class="hiddeninfo" id="hiddeninfo"></p>\n');

  h.push('<section class="modes">',
    '<button data-mode="quick" class="modebtn">Quick</button>',
    '<button data-mode="advanced" class="modebtn">Advanced</button>',
    '<button data-mode="custom" class="modebtn">Custom</button>',
    '<span id="customopts" hidden> ');
  for (const c of CLASSIFICATIONS) {
    h.push('<label><input type="checkbox" class="inc" value="', c, '" ', c === 'layout' ? '' : 'checked',
      '> ', esc(c), '</label> ');
  }
  h.push('<label><input type="checkbox" id="steppos"> step positions</label> ');
  h.push('<label><input type="checkbox" id="notepos"> note positions</label> ');
  h.push('<label><input type="checkbox" id="xmlpaths"> XML paths</label>');
  h.push('</span></section>\n');

  if (changeSet.warnings.length > 0) {
    h.push('<section class="warnings"><h2>Warnings</h2><ul>');
    for (const w of changeSet.warnings) {
      h.push('<li><code>', esc(w.code), '</code> ', esc(w.message), '</li>');
    }
    h.push('</ul></section>\n');
  }

  h.push('<section class="changes"><h2>Changes</h2>\n');
  if (changeSet.changes.length === 0) {
    h.push('<p class="nochanges">No differences — the transformations are semantically identical.</p>');
  }
  for (const c of changeSet.changes) renderChange(h, c);
  h.push('</section>\n');

  h.push('<footer>Generated by KTRDiff · schemaVersion ', String(changeSet.schemaVersion),
    ' · quick mode hides ', String(quick.hidden.length), ' change(s)</footer>\n');
  h.push('<script>', js(config.mode), '</script>\n');
  h.push('</body></html>');
  return h.join('');
}

function summaryCard(h: string[], label: string, count: number, cls: string): void {
  h.push('<div class="card ', cls, count === 0 ? ' zero' : '', '">',
    '<div class="num">', String(count), '</div>',
    '<div class="lbl">', esc(label), '</div></div>');
}

function renderChange(h: string[], c: Change): void {
  h.push('<details class="chg" data-cls="', c.classification,
    '" data-kind="', c.kind,
    '" data-prop="', esc(c.property ?? ''),
    '" data-volatile="', String(c.volatile), '">');
  h.push('<summary><span class="badge ', c.classification, '">',
    esc(c.classification), '</span> <span class="kind">',
    esc(c.kind), '</span> ');
  if (c.kind.startsWith('hop_')) {
    h.push('<strong>', esc(c.fromStep ?? '?'), ' → ', esc(c.toStep ?? '?'), '</strong>');
  } else if (c.beforeName !== null && c.afterName !== null && c.beforeName !== c.afterName) {
    h.push('<strong>', esc(c.beforeName), ' → ', esc(c.afterName), '</strong>');
  } else if (c.stepName !== null) {
    h.push('<strong>', esc(c.stepName), '</strong>');
    if (c.stepType !== null) h.push(' <em>[', esc(c.stepType), ']</em>');
  } else {
    h.push('<strong>', esc(c.entity), '</strong>');
  }
  if (c.field !== null) h.push(' · field <code>', esc(c.field), '</code>');
  if (c.property !== null) h.push(' · ', esc(c.property));
  h.push('</summary><div class="body">');
  if ((c.before !== null || c.after !== null) && !isTextBodyChange(c)) {
    h.push('<div class="vals">');
    h.push('<div class="val before"><span>before</span><pre>',
      esc(c.before === null ? '(none)' : javaValueOf(c.before)), '</pre></div>');
    h.push('<div class="val after"><span>after</span><pre>',
      esc(c.after === null ? '(none)' : javaValueOf(c.after)), '</pre></div>');
    h.push('</div>');
  }
  if (c.removedFragments.length > 0 || c.addedFragments.length > 0) {
    h.push('<pre class="diff">');
    for (const line of c.removedFragments) h.push('<span class="del">- ', esc(line), '</span>\n');
    for (const line of c.addedFragments) h.push('<span class="add">+ ', esc(line), '</span>\n');
    h.push('</pre>');
  }
  if (c.rawDiff !== null && c.rawDiff !== '') {
    h.push('<details class="raw"><summary>raw diff</summary><pre>', esc(c.rawDiff), '</pre></details>');
  }
  if (c.sourceXmlPath !== null) {
    h.push('<p class="xmlpath"><code>', esc(c.sourceXmlPath), '</code></p>');
  }
  if (c.confidence !== null) {
    h.push('<p class="conf">matching confidence: ', javaDoubleToString(c.confidence), '</p>');
  }
  h.push('</div></details>\n');
}

const ESCAPES: Readonly<Record<string, string>> = {
  '<': '&lt;', '>': '&gt;', '&': '&amp;', '"': '&quot;', "'": '&#39;',
};

/** HtmlRenderer.esc: null -> "", the five HTML-significant characters escaped. */
export function esc(s: string | null): string {
  if (s === null) return '';
  return s.replace(/[<>&"']/g, (ch) => ESCAPES[ch]!);
}

