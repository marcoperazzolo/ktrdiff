function js(initialMode: string): string {
  return "var MODE='" + esc(initialMode) + "';\n"
    + "function fmtOnly(c){var k=c.getAttribute('data-kind'),p=c.getAttribute('data-prop');"
    + "return (k==='sql_changed'&&p==='formatting')||(k==='script_changed'&&p==='whitespace');}\n"
    + "function visible(c){var cls=c.getAttribute('data-cls'),vol=c.getAttribute('data-volatile')==='true';\n"
    + " if(MODE==='advanced')return true;\n"
    + " if(MODE==='quick')return !vol&&cls!=='layout'&&!fmtOnly(c);\n"
    + " if(vol)return false;\n"
    + " var inc={};document.querySelectorAll('.inc').forEach(function(x){inc[x.value]=x.checked;});\n"
    + " if(!inc[cls])return false;\n"
    + " var k=c.getAttribute('data-kind');\n"
    + " if(k==='step_moved'&&!document.getElementById('steppos').checked)return false;\n"
    + " if(k==='note_moved'&&!document.getElementById('notepos').checked)return false;\n"
    + " return true;}\n"
    + "function apply(){var hid=0,tot=0;document.querySelectorAll('.chg').forEach(function(c){\n"
    + " if(c.classList.contains('raw'))return; tot++;\n"
    + " if(visible(c)){c.removeAttribute('hidden');}else{c.setAttribute('hidden','');hid++;}});\n"
    + "document.getElementById('hiddeninfo').textContent=hid>0?hid+' change(s) hidden by '+MODE+' mode':'';\n"
    + "document.querySelectorAll('.modebtn').forEach(function(b){b.classList.toggle('active',b.getAttribute('data-mode')===MODE);});\n"
    + "document.getElementById('customopts').hidden=(MODE!=='custom');\n"
    + "var sx=document.getElementById('xmlpaths').checked;\n"
    + "document.querySelectorAll('.xmlpath').forEach(function(x){x.style.display=sx?'':'none';});}\n"
    + "document.querySelectorAll('.modebtn').forEach(function(b){b.addEventListener('click',function(){MODE=b.getAttribute('data-mode');apply();});});\n"
    + "document.querySelectorAll('#customopts input').forEach(function(x){x.addEventListener('change',apply);});\n"
    + "apply();";
}
